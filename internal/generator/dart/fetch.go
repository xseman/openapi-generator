// FetchGenerator implements the dart-fetch generator.
//
// It produces a Dart client with no third-party runtime dependencies.
// HTTP requests are dispatched through a pluggable HttpSender; a
// dart:io HttpClient adapter is included by default.
type FetchGenerator struct {
	*BaseGenerator

	PubName         string
	PubVersion      string
	PubDescription  string
	PubAuthor       string
	PubHomepage     string
	PubRepository   string
	SdkConstraint   string
	UseDartIoSender bool

	// kinds is how each model is declared, by class (see modelKind); refs
	// the models' classes by schema name, for a property that refers to
	// one; aliases the property each alias model stands for.
	kinds   map[string]string
	refs    map[string]string
	aliases map[string]*codegen.CodegenProperty

	// types counts the type names declared so far, inline enums included.
	types map[string]int
}

// NewFetchGenerator creates a new Dart Fetch generator.
func NewFetchGenerator() *FetchGenerator {
	base := NewBaseGenerator()
	g := &FetchGenerator{
		BaseGenerator:   base,
		PubName:         "openapi",
		PubVersion:      "1.0.0",
		PubDescription:  "OpenAPI client generated by openapi-generator",
		UseDartIoSender: true,
		kinds:           map[string]string{},
		refs:            map[string]string{},
		aliases:         map[string]*codegen.CodegenProperty{},
		types:           map[string]int{},
	}

	g.ApiTemplateFiles["apis.mustache"] = ".dart"
	g.ModelTemplateFiles["models.mustache"] = ".dart"

	g.addExtraReservedWords()

	return g
}

// GetName returns the generator name.
func (g *FetchGenerator) GetName() string { return "dart-fetch" }

// GetTag returns the generator type.
func (g *FetchGenerator) GetTag() generator.GeneratorType { return generator.GeneratorTypeClient }

// GetHelp returns the help text.
func (g *FetchGenerator) GetHelp() string {
	return "Generates a Dart client library with no third-party runtime dependencies."
}

// ProcessOpts processes options and initializes the generator.
func (g *FetchGenerator) ProcessOpts() error {
	if g.DartConfig != nil {
		if g.DartConfig.PubName != "" {
			g.PubName = g.DartConfig.PubName
		}

		if g.DartConfig.PubVersion != "" {
			g.PubVersion = g.DartConfig.PubVersion
		}

		if g.DartConfig.PubDescription != "" {
			g.PubDescription = g.DartConfig.PubDescription
		}

		g.PubAuthor = g.DartConfig.PubAuthor
		g.PubHomepage = g.DartConfig.PubHomepage

		g.PubRepository = g.DartConfig.PubRepository
		if g.DartConfig.SdkConstraint != "" {
			g.SdkConstraint = g.DartConfig.SdkConstraint
		}

		g.UseDartIoSender = g.DartConfig.UseDartIoSender
	}

	g.PubName = sanitizePubName(g.PubName)

	g.SourceDir = ""
	g.ApiPackage = "lib/src/apis"
	g.ModelPackage = "lib/src/models"

	g.AdditionalProperties["pubName"] = g.PubName
	g.AdditionalProperties["pubVersion"] = g.PubVersion
	g.AdditionalProperties["pubDescription"] = g.PubDescription
	g.AdditionalProperties["pubAuthor"] = g.PubAuthor
	g.AdditionalProperties["pubHomepage"] = g.PubHomepage
	g.AdditionalProperties["pubRepository"] = g.PubRepository
	g.AdditionalProperties["sdkConstraint"] = g.SdkConstraint
	g.AdditionalProperties["useDartIoSender"] = g.UseDartIoSender

	g.SupportingFiles = append(g.SupportingFiles,
		generator.NewSupportingFile("library.mustache", "lib", g.PubName+".dart"),
		generator.NewSupportingFile("runtime.mustache", "lib/src", "runtime.dart"),
		generator.NewSupportingFile("pubspec.mustache", "", "pubspec.yaml"),
		generator.NewSupportingFile("analysis_options.mustache", "", "analysis_options.yaml"),
		generator.NewSupportingFile("gitignore.mustache", "", ".gitignore"),
		generator.NewSupportingFile("README.mustache", "", "README.md"),
	)

	return nil
}

// PostProcessModels declares every model for Dart: a class with allOf
// flattened, an enum, a typedef or a union wrapper.
func (g *FetchGenerator) PostProcessModels(models []*codegen.CodegenModel) []*codegen.CodegenModel {
	g.AdditionalProperties["dartHasModels"] = len(models) > 0

	bySchema := make(map[string]*codegen.CodegenModel, len(models))
	for _, m := range models {
		bySchema[m.SchemaName] = m
	}

	for _, m := range models {
		if len(m.AllOf) > 0 {
			flattenAllOf(m, bySchema)
		}

		kind := modelKind(m)
		g.kinds[m.Classname] = kind
		g.refs[m.SchemaName] = m.Classname
		g.types[m.Classname]++

		if kind == "alias" {
			g.aliases[m.Classname] = aliasOf(m)
		}
	}

	for _, m := range models {
		kind := g.kinds[m.Classname]

		ext := clone(m.VendorExtensions)
		ext["x-dart-doc"] = docLines(m.Description)
		ext["x-dart-enums"] = []map[string]any{}
		ext["x-dart-"+kind] = true

		switch kind {
		case "struct":
			fields, enums := g.structFields(m)
			ext["x-dart-fields"] = fields
			ext["x-dart-has-fields"] = len(fields) > 0
			ext["x-dart-enums"] = enums

		case "enum":
			ext["x-dart-enums"] = []map[string]any{
				enumDecl(m.Classname, EnumBaseType(m.AllowableValues, m.IsBoolean), m.AllowableValues, docLines(m.Description)),
			}

		case "alias":
			ext["x-dart-alias-type"] = g.typeOf(g.aliases[m.Classname], "")
		}

		m.VendorExtensions = ext
	}

	return models
}

// modelKind is how a model is declared: union (oneOf/anyOf), enum, struct
// (properties or allOf) or alias, a typedef of a list, map or scalar type.
//
// ponytail: a union is a wrapper of the decoded JSON value; the upgrade is
// a sealed class with a variant per member.
func modelKind(m *codegen.CodegenModel) string {
	vars, _ := m.AllowableValues["enumVars"].([]map[string]any)

	switch {
	case len(m.OneOf) > 0 || len(m.AnyOf) > 0:
		return "union"
	case m.IsEnum && len(vars) > 0 && EnumBaseType(m.AllowableValues, m.IsBoolean) != "Object?":
		return "enum"
	case len(m.AllVars) > 0 || len(m.AllOf) > 0:
		return "struct"
	}

	return "alias"
}

// aliasOf is the property a model without properties stands for, which
// types and converts a value of it.
func aliasOf(m *codegen.CodegenModel) *codegen.CodegenProperty {
	switch {
	case m.IsArray:
		return &codegen.CodegenProperty{IsArray: true, Items: m.Items}
	case m.AdditionalProperties != nil:
		return &codegen.CodegenProperty{IsMap: true, Items: m.AdditionalProperties}
	case m.IsEnum:
		// An enum of mixed types: any JSON value.
		return &codegen.CodegenProperty{}
	case m.DataType == "any" || m.IsAdditionalPropertiesTrue:
		return &codegen.CodegenProperty{OpenApiType: "object"}
	}

	return &codegen.CodegenProperty{
		IsString: m.IsString, IsDate: m.IsDate, IsDateTime: m.IsDateTime, IsBoolean: m.IsBoolean,
		IsInteger: m.IsInteger, IsLong: m.IsLong, IsNumber: m.IsNumber, IsFloat: m.IsFloat, IsDouble: m.IsDouble,
	}
}

// flattenAllOf gives a model built with allOf its ancestors' properties: the
// parser records the members only by name. Ancestors come first, in allOf
// order; a property declared again nearer the model replaces the inherited
// one in place, carrying its own required.
func flattenAllOf(m *codegen.CodegenModel, bySchema map[string]*codegen.CodegenModel) {
	m.AllVars = allVars(m, bySchema, map[string]bool{m.SchemaName: true})
}

func allVars(m *codegen.CodegenModel, bySchema map[string]*codegen.CodegenModel, visiting map[string]bool) []*codegen.CodegenProperty {
	var out []*codegen.CodegenProperty

	at := make(map[string]int)
	add := func(v *codegen.CodegenProperty) {
		if i, ok := at[v.BaseName]; ok {
			out[i] = v
			return
		}

		at[v.BaseName] = len(out)
		out = append(out, v)
	}

	for _, name := range m.AllOf {
		parent := bySchema[name]
		if parent == nil || visiting[name] {
			continue
		}

		visiting[name] = true

		for _, v := range allVars(parent, bySchema, visiting) {
			add(v)
		}

		delete(visiting, name)
	}

	for _, v := range m.Vars {
		add(v)
	}

	return out
}

// structFields types the properties of a struct model, writes the lines
// that read and write each in JSON, and declares its inline enums.
//
// ponytail: an optional nullable property sent as null and one left out
// both read as null, and null is left out on the way back; the upgrade is a
// wrapper type as go-fetch's Opt. Keys the schema does not declare
// (additionalProperties next to properties) are dropped; the upgrade is a
// map field for them.
func (g *FetchGenerator) structFields(m *codegen.CodegenModel) (fields, enums []map[string]any) {
	taken := make(map[string]int)
	fields, enums = []map[string]any{}, []map[string]any{}

	for _, v := range m.AllVars {
		name := uniqueName(taken, v.Name)

		enum, decl := g.inlineEnum(v, m.Classname+Camelize(v.Name, false)+"Enum")
		if decl != nil {
			enums = append(enums, decl)
		}

		t := g.typeOf(v, enum)
		key := Literal(v.BaseName)
		from := g.fromJSON(v, "json["+key+"]", enum)
		to := g.toJSON(v, name, enum)

		field := map[string]any{"doc": docLines(v.Description)}

		switch {
		case v.Required && !v.IsNullable:
			field["decl"] = "required final " + t + " " + name
			field["fromJson"] = name + ": " + from
			field["toJson"] = key + ": " + to

		case v.Required:
			field["decl"] = "required final " + Nullable(t) + " " + name
			field["fromJson"] = name + ": " + orNull("json["+key+"]", from)
			field["toJson"] = key + ": " + orNull(name, g.toJSON(v, name+"!", enum))

		default:
			field["decl"] = "final " + Nullable(t) + " " + name
			field["fromJson"] = name + ": " + orNull("json["+key+"]", from)
			field["toJson"] = optionalEntry(key, name, g.toJSON(v, "v", enum))
		}

		fields = append(fields, field)
	}

	return fields, enums
}

// optionalEntry is the map entry of key that leaves out a null name;
// expr converts v, the value when it is not null.
func optionalEntry(key, name, expr string) string {
	if expr == "v" {
		return key + ": ?" + name
	}

	return "if (" + name + " case final v?) " + key + ": " + expr
}

// orNull is expr, the conversion of x, for an x that may be null; x itself
// when the conversion changes nothing.
func orNull(x, expr string) string {
	if expr == x || expr == x+"!" {
		return x
	}

	return x + " == null ? null : " + expr
}

// leaf is the property at the end of p's lists and maps.
func leaf(p *codegen.CodegenProperty) *codegen.CodegenProperty {
	for p != nil && (p.IsArray || p.IsMap) {
		p = p.Items
	}

	return p
}

// inlineEnum declares an enum called name for the values p, or the element
// of its lists and maps, lists inline, and returns the name it took; "" and
// nil when p has none, refers to an enum model or mixes types.
func (g *FetchGenerator) inlineEnum(p *codegen.CodegenProperty, name string) (string, map[string]any) {
	l := leaf(p)
	if l == nil || !l.IsEnum || g.modelOf(l) != "" {
		return "", nil
	}

	vars, _ := l.AllowableValues["enumVars"].([]map[string]any)

	base := EnumBaseType(l.AllowableValues, l.IsBoolean)
	if base == "Object?" || len(vars) == 0 {
		return "", nil
	}

	name = uniqueName(g.types, name)

	return name, enumDecl(name, base, l.AllowableValues, []string{"/// " + name + " is a value of " + p.BaseName + "."})
}

// enumDecl describes an enum for the template: its values' type and each
// value's name and literal.
func enumDecl(name, base string, allowable map[string]any, doc []string) map[string]any {
	vars, _ := allowable["enumVars"].([]map[string]any)
	unescape := strings.NewReplacer(`\\`, `\`, `\'`, `'`, `\n`, "\n", `\r`, "\r", ` `, " ", ` `, " ")

	taken := map[string]int{"values": 1, "value": 1, "index": 1, "name": 1, "fromJson": 1, "toJson": 1, "hashCode": 1, "runtimeType": 1}
	values := make([]map[string]any, 0, len(vars))

	for _, v := range vars {
		literal, _ := v["value"].(string)
		if base == "String" {
			literal = Literal(unescape.Replace(literal))
		}

		// The parser names values in PascalCase, Dart in lowerCamelCase; a
		// leading underscore would make the value private to its file.
		member, _ := v["name"].(string)
		member = strings.TrimLeft(member, "_")

		if member != "" {
			member = strings.ToLower(member[:1]) + member[1:]
		}

		switch {
		case member == "" || unicode.IsDigit(rune(member[0])):
			member = "n" + member
		case ReservedWords[strings.ToLower(member)]:
			member += "_"
		}

		values = append(values, map[string]any{"name": uniqueName(taken, member), "literal": literal})
	}

	return map[string]any{"name": name, "base": base, "values": values, "doc": doc}
}

// uniqueName is name, numbered from its second use in taken.
func uniqueName(taken map[string]int, name string) string {
	unique := name
	for n := 2; taken[unique] > 0; n++ {
		unique = name + strconv.Itoa(n)
	}

	taken[unique]++

	return unique
}

// docLines is text as the lines of a doc comment.
func docLines(text string) []string {
	lines := []string{}

	text = strings.TrimSpace(strings.ReplaceAll(text, "\r", ""))
	if text == "" {
		return lines
	}

	for _, line := range strings.Split(text, "\n") {
		lines = append(lines, strings.TrimRight("/// "+line, " \t"))
	}

	return lines
}

// clone copies vendor extensions before they are written to: the parser
// shares the spec's own map between copies of an operation.
func clone(ext map[string]any) map[string]any {
	if ext == nil {
		return map[string]any{}
	}

	return maps.Clone(ext)
}

// PostProcessOperations types each operation's parameters, body and result
// for the api template and writes the expressions that send and read them.
func (g *FetchGenerator) PostProcessOperations(ops []*codegen.CodegenOperation) []*codegen.CodegenOperation {
	taken := make(map[string]bool, len(ops))
	for _, op := range ops {
		taken[op.Nickname] = true
	}

	for _, op := range ops {
		g.escapeOperationId(op, taken)

		ext := clone(op.VendorExtensions)
		ext["x-dart-path"] = Literal(op.Path)
		g.paramExtensions(op, ext)
		g.resultExtensions(op, ext)
		op.VendorExtensions = ext
	}

	return ops
}

// paramExtensions gives each parameter its declaration, its key on the
// wire and the expression of its JSON value, and the operation the
// signature and arguments its three methods share.
func (g *FetchGenerator) paramExtensions(op *codegen.CodegenOperation, ext map[string]any) {
	enums := []map[string]any{}
	files := false

	var signature, args []string

	for _, p := range op.AllParams {
		prop := asProperty(p)

		enum, decl := g.inlineEnum(prop, Camelize(op.Nickname, false)+Camelize(p.ParamName, false)+"Enum")
		if decl != nil {
			enums = append(enums, decl)
		}

		t := g.typeOf(prop, enum)
		optional := !p.Required || p.IsNullable
		value := g.toJSON(prop, p.ParamName, enum)

		// A file is its bytes, which JSON has no type for: a part of a
		// form with its name, the whole of a body.
		switch {
		case p.IsFormParam && p.IsArray && p.IsFile:
			t = "List<UploadFile>"
		case p.IsFormParam && (p.IsFile || p.IsBinary):
			t = "UploadFile"
		case p.IsFile, p.IsBinary, p.IsBodyParam && p.DataType == "Blob" && !p.IsModel:
			t = "Uint8List"
		}

		files = files || p.IsFormParam && (p.IsFile || p.IsBinary)

		if optional {
			t = Nullable(t)
		}

		if p.Required && p.IsNullable {
			value = orNull(p.ParamName, value)
		}

		pext := clone(p.VendorExtensions)
		key := Literal(p.BaseName)
		pext["x-dart-key"] = key
		pext["x-dart-json"] = value
		pext["x-dart-optional"] = !p.Required
		pext["x-dart-placeholder"] = Literal("{" + p.BaseName + "}")
		pext["x-dart-explode"] = strconv.FormatBool(p.IsExplode)
		pext["x-dart-style"] = Literal(p.Style) + ", " + strconv.FormatBool(p.IsExplode)
		pext["x-dart-wire"] = key + ", " + Literal(p.Style) + ", " + strconv.FormatBool(p.IsExplode)

		if p.IsBodyParam {
			pext["x-dart-content-type"], pext["x-dart-body"] = body(p, t, value)
		}

		p.VendorExtensions = pext

		required := ""
		if p.Required {
			required = "required "
		}

		signature = append(signature, "        "+required+t+" "+p.ParamName+",\n")
		args = append(args, p.ParamName+": "+p.ParamName)
	}

	// A form with a file goes as multipart whatever the spec declares, as
	// url-encoding has no place for its bytes.
	multipart := len(op.FormParams) > 0 && (op.IsMultipart || files)
	ext["x-dart-multipart"] = multipart
	ext["x-dart-form"] = len(op.FormParams) > 0 && !multipart
	ext["x-dart-enums"] = enums
	ext["x-dart-args"] = strings.Join(args, ", ")
	ext["x-dart-signature"] = ""

	if len(signature) > 0 {
		ext["x-dart-signature"] = "{\n" + strings.Join(signature, "") + "    }"
	}
}

// body is the Content-Type a body parameter goes out with and the
// expression of the bytes or text sent: JSON unless its media type or its
// type says otherwise.
func body(p *codegen.CodegenParameter, t, value string) (contentType, expr string) {
	contentType = p.ContentType
	if contentType == "" {
		contentType = "application/json"
	}

	switch {
	case strings.TrimSuffix(t, "?") == "Uint8List":
		expr = value
	case !isJSONMime(contentType) && strings.TrimSuffix(t, "?") == "String":
		expr = value
	default:
		expr = "jsonEncode(" + value + ")"
	}

	return Literal(contentType), expr
}

// isJSONMime reports whether a media type carries JSON: application/json,
// a +json suffix, or any type (*/*).
func isJSONMime(mediaType string) bool {
	mediaType, _, _ = strings.Cut(mediaType, ";")
	mediaType = strings.ToLower(strings.TrimSpace(mediaType))

	return mediaType == "application/json" || mediaType == "*/*" || strings.HasSuffix(mediaType, "+json")
}

// asProperty is parameter p as a property, for DartType and the converter.
func asProperty(p *codegen.CodegenParameter) *codegen.CodegenProperty {
	return &codegen.CodegenProperty{
		BaseName: p.BaseName, DataType: p.DataType, Ref: p.Ref, ComposedSchemas: p.ComposedSchemas,
		IsModel: p.IsModel, IsArray: p.IsArray, IsMap: p.IsMap, Items: p.Items,
		IsEnum: p.IsEnum, AllowableValues: p.AllowableValues,
		IsString: p.IsString, IsDate: p.IsDate, IsDateTime: p.IsDateTime,
		IsInteger: p.IsInteger, IsLong: p.IsLong, IsNumber: p.IsNumber, IsFloat: p.IsFloat, IsDouble: p.IsDouble,
		IsBoolean: p.IsBoolean,
	}
}

// resultExtensions types the operation's result and writes the expression
// that reads it from the response: bytes, text, or JSON converted as a
// model's property is. A result a 2xx status may send without a body, and
// a nullable one, is nullable.
func (g *FetchGenerator) resultExtensions(op *codegen.CodegenOperation, ext map[string]any) {
	prop := op.ReturnProperty
	if prop == nil && g.kinds[op.ReturnType] != "" {
		// A $ref, which the parser names but leaves untyped.
		prop = &codegen.CodegenProperty{IsModel: true, DataType: op.ReturnType}
	}

	result := map[string]any{"type": "void"}
	ext["x-dart-return"] = result

	if g.streamResult(op, result) {
		return
	}

	switch {
	case op.IsResponseBinary:
		result["type"] = "Uint8List"
		result["bytes"] = true

		return

	case op.ReturnType == "":
		result["void"] = true

		return
	}

	t := g.typeOf(prop, "")
	decode := g.fromJSON(prop, "$json", "")

	empty := prop != nil && prop.IsNullable

	for _, r := range op.Responses {
		if strings.HasPrefix(r.Code, "2") && r.DataType == "" {
			empty = true
		}
	}

	if empty {
		t = Nullable(t)
		decode = orNull("$json", decode)
	}

	result["type"] = t

	if strings.TrimSuffix(t, "?") == "String" {
		result["text"] = true
		result["nullable"] = empty

		return
	}

	result["json"] = true
	result["decode"] = decode

	if other := other2xx(op); t != "Object?" && other != "" {
		result["other"] = other
	}
}

// streamResult types an operation whose 2xx response streams its items
// (x-stream, see the parser's streamItem) and reports whether it does: JSON
// Lines as a Stream of the item type, server-sent events as one of
// ServerSentEvent of it. Another streamed media type has only its Raw
// method's bytes.
func (g *FetchGenerator) streamResult(op *codegen.CodegenOperation, result map[string]any) bool {
	for _, r := range op.Responses {
		item, _ := r.VendorExtensions["x-stream-item"].(*codegen.CodegenProperty)
		mediaType, _ := r.VendorExtensions["x-stream"].(string)
		mediaType, _, _ = strings.Cut(mediaType, ";")

		if !r.Is2xx || item == nil {
			continue
		}

		t := g.typeOf(item, "")
		if item.IsNullable {
			t = Nullable(t)
		}

		switch mediaType {
		case "application/jsonl", "application/x-ndjson":
			result["type"] = t
			result["decode"] = "decodeLines($res, ($json) => " + g.itemFromJSON(item, "$json", "") + ")"

		case "text/event-stream":
			result["type"] = "ServerSentEvent<" + t + ">"
			result["decode"] = "decodeEvents($res, ($data) => " + g.itemFromJSON(item, "jsonDecode($data)", "") + ")"

			if t == "String" {
				result["decode"] = "decodeEvents($res, ($data) => $data)"
			}

		default:
			continue
		}

		result["stream"] = true

		return true
	}

	return false
}

// other2xx lists the 2xx statuses whose body is of another type than the
// result (a 201 Order next to a 202 Problem), comma-separated: the typed
// method throws them as an ApiException holding that body, which the result
// cannot.
func other2xx(op *codegen.CodegenOperation) string {
	var result string

	codes := []string{}

	for _, r := range op.Responses {
		if _, err := strconv.Atoi(r.Code); err != nil || !r.Is2xx || r.DataType == "" {
			continue
		}

		if result == "" {
			result = r.DataType
		}

		if r.DataType != result {
			codes = append(codes, r.Code)
		}
	}

	return strings.Join(codes, ", ")
}

// apiMembers are the members of BaseApi and Object, which an operation's
// method of the same name would override.
var apiMembers = []string{
	"configuration", "buildUri", "request", "queryValues",
	"toString", "hashCode", "runtimeType", "noSuchMethod",
}

// escapeOperationId renames an operation whose method would clash with
// the Raw or RequestOpts method the api template writes for another one
// (taken, the operations' names), with a member the API class inherits, or
// with a Dart reserved word.
func (g *FetchGenerator) escapeOperationId(op *codegen.CodegenOperation, taken map[string]bool) {
	for _, suffix := range []string{"Raw", "RequestOpts"} {
		if base, ok := strings.CutSuffix(op.Nickname, suffix); ok && taken[base] {
			op.Nickname += "Method"

			return
		}
	}

	if g.IsReservedWord(op.Nickname) || slices.Contains(apiMembers, op.Nickname) {
		op.Nickname += "_"
	}
}

// addExtraReservedWords reserves the names the generated runtime and every
// model declare, which a model or a property must not take.
func (g *FetchGenerator) addExtraReservedWords() {
	extra := []string{
		"BaseApi", "Configuration", "ApiException", "RequiredParameterError",
		"HttpRequest", "HttpResponse", "HttpSender", "HttpMethod",
		"JsonApiResponse", "VoidApiResponse", "TextApiResponse", "BlobApiResponse",
		"Middleware", "RequestContext", "ResponseContext",
		"defaultHttpSender", "encodeFormData", "encodeQueryParam", "UploadFile", "Multipart", "ServerSentEvent",
		// Members every class has, or a model declares: a property of the
		// same name would override them.
		"toJson", "fromJson", "hashCode", "runtimeType", "toString", "noSuchMethod",
	}
	for _, w := range extra {
		g.ReservedWords[strings.ToLower(w)] = true
	}
}

// sanitizePubName ensures the package name is a valid Dart pub package
// identifier: lower_snake_case, starts with a letter, only [a-z0-9_].
func sanitizePubName(name string) string {
	if name == "" {
		return "openapi"
	}

	name = Underscore(name)

	var out strings.Builder

	for i, r := range name {
		switch {
		case r >= 'a' && r <= 'z':
			out.WriteRune(r)
		case r >= '0' && r <= '9':
			if i == 0 {
				out.WriteByte('_')
			}

			out.WriteRune(r)

		case r == '_':
			out.WriteRune(r)
		}
	}

	if out.Len() == 0 {
		return "openapi"
	}

	return out.String()
}
