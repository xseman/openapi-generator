package template

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestFormatGo(t *testing.T) {
	src := `// Code generated by openapi-generator. DO NOT EDIT.

// Package x is a package used in a test.
package x

import (
	"encoding/json"
	"fmt"
	str "strings"
	_ "embed"
	"net/http"
)

func f() string {   return fmt.Sprint(str.ToUpper("a")) }
`

	got, err := formatGo([]byte(src))
	if err != nil {
		t.Fatal(err)
	}

	want := `// Code generated by openapi-generator. DO NOT EDIT.

// Package x is a package used in a test.
package x

import (
	_ "embed"
	"fmt"
	str "strings"
)

func f() string { return fmt.Sprint(str.ToUpper("a")) }
`
	if string(got) != want {
		t.Errorf("formatGo:\n%s\nwant:\n%s", got, want)
	}
}

func TestFormatGoDropsEveryImport(t *testing.T) {
	got, err := formatGo([]byte("package x\n\nimport \"fmt\"\n\nconst a = 1\n"))
	if err != nil {
		t.Fatal(err)
	}

	if want := "package x\n\nconst a = 1\n"; string(got) != want {
		t.Errorf("formatGo = %q, want %q", got, want)
	}
}

func TestRenderToFileGoSyntaxError(t *testing.T) {
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "x.mustache"), []byte("package x\n\nfunc {\n"), 0o600); err != nil {
		t.Fatal(err)
	}

	out := filepath.Join(dir, "x.go")

	err := NewEngine(dir).RenderToFile("x.mustache", map[string]any{}, out)
	if err == nil || !strings.Contains(err.Error(), out) {
		t.Fatalf("RenderToFile error = %v, want one naming %s", err, out)
	}

	if data, _ := os.ReadFile(out); string(data) != "package x\n\nfunc {\n" {
		t.Errorf("unformatted source not written: %q", data)
	}
}
