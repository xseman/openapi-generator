// applyDartAdditionalProperties maps CLI / config additional-property values
// onto a DartFetchConfig.
func applyDartAdditionalProperties(dc *config.DartFetchConfig, props map[string]any) {
	if v, ok := props["pubName"].(string); ok {
		dc.PubName = v
	}
	if v, ok := props["pubVersion"].(string); ok {
		dc.PubVersion = v
	}
	if v, ok := props["pubDescription"].(string); ok {
		dc.PubDescription = v
	}
	if v, ok := props["pubAuthor"].(string); ok {
		dc.PubAuthor = v
	}
	if v, ok := props["pubHomepage"].(string); ok {
		dc.PubHomepage = v
	}
	if v, ok := props["pubRepository"].(string); ok {
		dc.PubRepository = v
	}
	if v, ok := props["sdkConstraint"].(string); ok {
		dc.SdkConstraint = v
	}
	if v, ok := props["useDartIoSender"].(bool); ok {
		dc.UseDartIoSender = v
	}
	if v, ok := props["modelPropertyNaming"].(string); ok {
		dc.ModelPropertyNaming = v
	}
	if v, ok := props["sortParamsByRequiredFlag"].(bool); ok {
		dc.SortParamsByRequiredFlag = v
	}
	if v, ok := props["licenseName"].(string); ok {
		dc.LicenseName = v
	}
	if v, ok := props["licenseUrl"].(string); ok {
		dc.LicenseUrl = v
	}
}

// toDartImports converts a list of model class names into the
// {classname, filename} maps expected by the Dart templates.
func toDartImports(imports []string, gen *dart.FetchGenerator) []map[string]string {
	result := make([]map[string]string, 0, len(imports))
	for _, imp := range imports {
		className := gen.ToModelName(imp)
		if className == "" || gen.IsPrimitive(className) {
			continue
		}
		result = append(result, map[string]string{
			"classname": className,
			"className": className,
			"filename":  gen.ToModelFilename(className),
		})
	}
	return result
}

// generateDartModelIndex emits the per-folder barrel for lib/src/models.
func generateDartModelIndex(models []*generator.CodegenModel, gen *dart.FetchGenerator) string {
	var sb strings.Builder
	sb.WriteString("// Auto-generated by openapi-generator. Do not edit.\n\n")
	for _, m := range models {
		fmt.Fprintf(&sb, "export '%s.dart';\n", gen.ToModelFilename(m.Classname))
	}
	return sb.String()
}

// generateDartApiIndex emits the per-folder barrel for lib/src/apis.
func generateDartApiIndex(opsByTag map[string][]*generator.CodegenOperation, gen *dart.FetchGenerator) string {
	var sb strings.Builder
	sb.WriteString("// Auto-generated by openapi-generator. Do not edit.\n\n")
	for _, tag := range sortedTags(opsByTag) {
		apiClassname := gen.ToApiName(tag)
		fmt.Fprintf(&sb, "export '%s.dart';\n", gen.ToApiFilename(apiClassname))
	}
	return sb.String()
}

